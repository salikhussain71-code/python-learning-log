# Code 1 - for loop with list literal
for i in [0, 1, 2]:
    print("meow")

# Code 2 - for loop with range
for i in range(3):
    print("meow")

# Code 3 - list indexing
students = ["Salik", "shakir", "amil"]
print(students[0])
print(students[1])
print(students[2])

# Code 4 - for loop over list
students = ["Salik", "shakir", "amil"]
for student in students:
    print(student)

# Code 5 - for loop with range + len
students = ["Salik", "shakir", "amil"]
for i in range(len(students)):
    print(students[i])